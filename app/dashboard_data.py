# ---------------------------------------------------------------------------
# Artifact availability helpers
# ---------------------------------------------------------------------------

def artifact_exists(path: Path) -> bool:
    """
    Return True when a dashboard artifact exists.
    """

    return path.exists()


def get_artifact_status() -> dict[str, bool]:
    """
    Return availability status for all dashboard artifacts.
    """

    paths = {
        "baseline_results": BASELINE_RESULTS_PATH,
        "xgboost_results": XGBOOST_RESULTS_PATH,
        "cost_threshold_results": COST_THRESHOLD_RESULTS_PATH,
        "cost_sensitivity_results": COST_SENSITIVITY_RESULTS_PATH,
        "calibration_results": CALIBRATION_RESULTS_PATH,
        "calibration_test_results": CALIBRATION_TEST_RESULTS_PATH,
        "risk_scoring_config": RISK_SCORING_CONFIG_PATH,
        "decision_policy": DECISION_POLICY_PATH,
        "explanation_report": EXPLANATION_REPORT_PATH,
    }

    return {
        name: artifact_exists(path)
        for name, path in paths.items()
    }