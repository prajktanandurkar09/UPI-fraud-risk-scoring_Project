"""
UPI-SHIELD dashboard data layer.

This module is responsible only for loading existing project artifacts
and experiment results for the Streamlit dashboard.

No metrics are fabricated here.
No model is trained here.
No prediction is performed here.

All dashboard analytics are sourced from files already generated by
the UPI-SHIELD experimentation pipeline.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


# ---------------------------------------------------------------------------
# Project paths
# ---------------------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parent.parent

RESULTS_DIR = PROJECT_ROOT / "experiments" / "results"
MODELS_DIR = PROJECT_ROOT / "models"


# ---------------------------------------------------------------------------
# Result/configuration paths
# ---------------------------------------------------------------------------

BASELINE_RESULTS_PATH = RESULTS_DIR / "baseline_results.json"

XGBOOST_RESULTS_PATH = RESULTS_DIR / "xgboost_results.json"

COST_THRESHOLD_RESULTS_PATH = (
    RESULTS_DIR / "cost_sensitive_threshold_results.json"
    if (RESULTS_DIR / "cost_sensitive_threshold_results.json").exists()
    else RESULTS_DIR / "cost_aware_results.json"
)

COST_SENSITIVITY_RESULTS_PATH = (
    RESULTS_DIR / "cost_sensitivity_results.json"
)

CALIBRATION_RESULTS_PATH = RESULTS_DIR / "calibration_results.json"

CALIBRATION_TEST_RESULTS_PATH = (
    RESULTS_DIR / "calibration_test_results.json"
)

RISK_SCORING_CONFIG_PATH = (
    MODELS_DIR / "risk_scoring_config.json"
)

DECISION_POLICY_PATH = (
    MODELS_DIR / "decision_policy.json"
)

EXPLANATION_REPORT_PATH = (
    RESULTS_DIR / "explanation_report.json"
)


# ---------------------------------------------------------------------------
# Generic JSON loader
# ---------------------------------------------------------------------------

def _load_json(path: Path) -> dict[str, Any] | list[Any] | None:
    """
    Load a JSON artifact.

    Returns None when the file does not exist or cannot be decoded.
    The dashboard can then show an appropriate missing-file message
    rather than crashing.
    """

    if not path.exists():
        return None

    try:
        with path.open("r", encoding="utf-8") as file:
            return json.load(file)
    except (OSError, json.JSONDecodeError):
        return None


# ---------------------------------------------------------------------------
# Missing-file helper
# ---------------------------------------------------------------------------

def missing_file_notice(
    label: str,
    path: Path,
) -> str:
    """
    Return a user-friendly message for a missing dashboard artifact.
    """

    return (
        f"{label} is not available. "
        f"Expected file: {path}"
    )


